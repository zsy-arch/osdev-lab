/* 架构无关的页表操作接口——Lab4 引入。
 *
 * 和 kalloc.h（Lab3）同一个分工原则：这里只声明"做什么"（建映射、查
 * 映射、启用分页),不管"怎么做"。x86_64 的 4 级页表（PML4/PDPT/PD/PT,
 * 每级 512 项,每项 8 字节)和 riscv64 Sv39 的 3 级页表（同样每级 512 项,
 * 每项 8 字节,但 PTE 位布局完全不同——riscv64 用 R/W/X 三个独立位表示
 * 权限,叶子节点由"至少一个 RWX 位置 1"识别；x86_64 用一个 Present 位
 * +一个 R/W 位+一个 NX 位,叶子节点由"页表层级+PS 位"识别)各自在
 * pagetable_x86_64.c / pagetable_riscv64.c 里实现同一套函数签名。
 *
 * 权限用一组架构无关的标志位表示（PTE_FLAG_*),调用者不需要知道目标
 * 架构的 PTE 具体是哪个 bit——这组标志位在各自的 .c 文件内部翻译成
 * 真正的硬件 PTE 位,翻译细节不在这里,因为翻译本身就是"两个架构不一样
 * 的地方"，属于 solution/<arch>/pagetable.c 的教学内容。
 */
#ifndef OSDEV_PAGETABLE_H
#define OSDEV_PAGETABLE_H

#include "types.h"

#define PTE_FLAG_WRITABLE   (1u << 0)  /* 可写；不设的话只读。 */
#define PTE_FLAG_EXECUTABLE (1u << 1)  /* 可取指执行；不设的话不可执行
                                         * （x86_64 需要 EFER.NXE 置位
                                         * 才能真正生效,riscv64 天然
                                         * per-page 支持,见各自实现）。 */
#define PTE_FLAG_USER       (1u << 2)  /* 用户态可访问；本 Lab 不用
                                         * （还没有用户态),Lab6 会用到,
                                         * 现在先把标志位定义好。 */

/* 建立一段虚拟地址到物理地址的映射,每次调用映射恰好一页（4KiB)。
 * 这是 ROADMAP 明确要求的"手写的映射一段虚拟地址到指定物理地址的
 * 函数"——调用者想映射多页,自己循环调用,每次 vaddr/paddr 各加
 * PAGE_SIZE（PAGE_SIZE 定义在 kalloc.h,4KiB,两个架构公用同一个粒度）。
 *
 * root 是页表根节点的物理地址（x86_64 是 PML4 基址,riscv64 是 Sv39
 * 顶层页表基址),不是"当前生效的那份"（当前生效的那份由 CR3/satp 决定,
 * 这里传的 root 可以是还没启用的一份,用于提前搭好、再一次性切换)。
 * 遇到某一级页表项还不存在（下一级页表还没建),内部会调 kalloc_page()
 * 分配一个新的页表节点、清零、挂上去——这是本函数会隐式触发物理页
 * 分配的唯一副作用,失败（kalloc_page 返回 NULL)时 panic,不返回错误码
 * （教学取向：调用者不需要处理"页表节点分配失败"这种在教学场景下
 * 几乎不会发生的情况,真实内核会更谨慎地传播这个错误)。
 *
 * vaddr/paddr 必须已经是页对齐的（调用者负责,不做防御性检查——这是
 * 本课程一贯的取向,内部调用点自己保证对齐,不需要在这个热点函数里
 * 反复校验)。 */
void pagetable_map(uintptr_t root, uintptr_t vaddr, uintptr_t paddr,
                    uint32_t flags);

/* 查一段虚拟地址当前映射到哪个物理地址,主要用于测试/调试断言（比如
 * "刚 map 完的地址,查出来的物理地址应该和传进去的一致")。没有映射
 * （某一级页表项不存在,或者存在但标记为不可用)返回 0——0 不是一个
 * 合法的物理页地址（第 0 页从 Lab3 起就被排除在可分配范围之外,见
 * kalloc_add_region 的取整逻辑),用它当"没有映射"的哨兵值不会跟正常
 * 返回值冲突。 */
uintptr_t pagetable_lookup(uintptr_t root, uintptr_t vaddr);

/* 分配一个全新的、清零的页表根节点,返回它的物理地址。内部就是
 * kalloc_page() + 清零,单独包一层是因为"新页表根节点必须整页清零"
 * 这个前提容易漏（清零前的物理页内容是上一个使用者留下的垃圾,当成
 * 页表用会把垃圾字节解释成页表项,大概率指向不存在的物理地址,查表
 * 时直接读飞),包成一个函数确保这一步不会被漏掉。 */
uintptr_t pagetable_create(void);

/* 把 root 对应的页表安装为当前生效的页表（写 CR3 / satp),并打开分页
 * 硬件（如果还没开——x86_64 从 Lab2 起分页就已经是开着的,这里只是
 * 换根；riscv64 在此之前 satp=0,即分页从未启用过,这里是第一次真正
 * 打开)。调用之后,CPU 取指/访存全部经过 root 这份页表翻译,所以调用
 * 之前必须确保当前 PC 所在的地址在 root 里有有效映射,否则这条指令
 * 执行完的下一条指令就会立刻缺页——本 Lab 的 boot.S 会按这个前提
 * 安排调用时机,见各架构 boot.S 顶部注释。 */
void pagetable_activate(uintptr_t root);

/* Lab7 新增：把"内核自己那份根页表"里覆盖内核镜像+自映射范围的顶级
 * 页表项,原样复制进一个刚创建的新根页表（通常是某个进程自己的
 * pagetable_create() 返回值)。
 *
 * 动机：Lab7 每个进程都有自己独立的页表（不再像 Lab6 那样全程共用
 * 同一份 CR3),但内核代码本身（陷入处理、系统调用分发、调度器……)
 * 必须在*任何*进程的页表生效时都能被同样地取指执行——不然 SYSCALL/
 * 中断门陷入内核的第一条指令就会 #PF（当前 CR3/satp 已经是进程自己
 * 的表,如果这份表里没有内核那部分映射,内核代码所在的那些虚拟地址
 * 在这份表里根本不存在)。真实内核的标准做法是"每个用户地址空间的
 * 高地址部分永远长得和内核页表一样"，本课程用最直接的方式实现这一点：
 * 复制顶级页表项本身,而不是逐页 pagetable_map()——顶级页表项本来就
 * 指向下一级页表节点,复制这一项等于让新表和内核表在这段范围内共享
 * 同一批下级页表节点（不是深拷贝出两份独立的页表树),后续内核镜像
 * 本身不会再变化（不会有新的内核代码在运行时被映射进来),共享是安全
 * 的,也避免了给每个进程各自复制一整套页表节点的开销。
 *
 * 只复制"内核范围"，不是整份表：顶级页表每一项覆盖一段很大的地址
 * 范围（x86_64 每个 PML4 项覆盖 512GiB,riscv64 每个顶级项覆盖 1GiB
 * 出头),内核镜像+自映射落在其中很小一部分顶级项里,各架构自己决定
 * 具体复制哪些顶级项索引（不通过参数传,因为这是纯粹的架构细节,调用
 * 者不需要知道)。
 *
 * 依赖 pagetable_set_kernel_root() 提前告知"内核自己那份根页表在哪"——
 * kernel_boot() 必须在调用这个函数之前先调用过那个 setter 一次,否则
 * 复制出来的是垃圾（未设置时的默认值)。 */
void pagetable_copy_kernel_range(uintptr_t dst_root);

/* 告知本模块"内核自己的根页表物理地址是什么",供 pagetable_copy_
 * kernel_range() 内部使用。kernel_boot() 在 pagetable_create()+把
 * 内核镜像本身映射好、但还没有 pagetable_activate() 之前调用一次
 * 即可（此后这份表不会再变根,后续每个进程各自的新表都是从这份表
 * 复制内核范围出来的)。 */
void pagetable_set_kernel_root(uintptr_t root);

/* Lab7 新增：撤销一段虚拟地址的映射,返回撤销前那里映射着的物理地址
 * （跟 pagetable_lookup() 一样用 0 表示"本来就没有映射"——调用者据此
 * 判断是否需要 kfree_page() 那个物理页,不判断的话,对一个本来没映射
 * 的地址调用本函数会得到 0,传给 kfree_page() 是明确的错误用法,调用者
 * 必须自己先检查)。
 *
 * 动机：sys_exec() 需要在往同一个虚拟地址（USER_PROG_VADDR/用户栈)
 * 重新 pagetable_map() 之前,先释放掉旧的映射关系和旧的物理页——不这样
 * 做的话,对同一个虚拟地址第二次 pagetable_map() 会导致"一个虚拟地址
 * 被映射了两次"这种不一致状态（旧 PTE 指向的物理页也不会被回收,造成
 * 内存泄漏),这正是 pagetable_map() 自己文档注释里指出的、本课程范围
 * 内没有实现的语义缺口——本函数把这个缺口补上,但只做"清空一个已经
 * 存在的叶子 PTE",不处理"清空之后,它所在的中间层节点是不是变空了、
 * 要不要连中间层节点一起释放"这种更完整的页表回收（跟 sys_wait() 里
 * "本 Lab 不回收页表本身"是同一个教学取向,那里注释已经说明)。
 *
 * 只清叶子层（PT 里的那一项),不处理"中间层页表项不存在"的情况——
 * 如果 vaddr 对应的中间层结构（PML4E/PDPTE/PDE)有任何一级还没建过,
 * 说明这段地址原本就没有映射,直接返回 0,不会（也不需要)现场创建
 * 中间层节点后再判断"叶子项是不是 Present"——这跟 pagetable_lookup()
 * 用 alloc_missing=false 调 walk() 是同一个道理。 */
uintptr_t pagetable_unmap(uintptr_t root, uintptr_t vaddr);

#endif /* OSDEV_PAGETABLE_H */
