/* Lab9：块设备抽象——整个文件系统只通过这两个函数碰磁盘。
 *
 * 这份头文件在 x86_64 和 riscv64 目录下内容完全相同（Makefile 有一条
 * check-fs-iface 规则用 cmp 守住这一点），但它们*背后的实现*毫无共同点：
 *
 *   x86_64  ide.c     —— ATA PIO。outb() 往几个 I/O 端口写 LBA 和命令，
 *                        然后 insw() 从数据端口一个字一个字把 512 字节
 *                        搬进内存。数据走的是 CPU，每个字都过一遍寄存器。
 *   riscv64 virtio.c  —— virtio-blk over MMIO。往一组共享内存里的环形
 *                        队列放一个"请求描述符"，写一下通知寄存器，然后
 *                        等设备自己把数据 DMA 进我们给的缓冲区。数据不走
 *                        CPU，CPU 只负责下达和确认。
 *
 * 这是本 Lab 最值得带走的架构对照：同一个 blk_read(blkno, buf) 语义,
 * 一边是"CPU 亲自搬字节"的程序化 I/O，一边是"CPU 下单、设备自己搬"的
 * 描述符式 DMA。真实硬件的演进方向就是后者（AHCI、NVMe 都是环形队列 +
 * DMA），ATA PIO 属于必须能看懂但早已不用于性能路径的历史接口。fs.c
 * 对这个差异一无所知，因此两个架构下的 fs.c 可以逐字节相同。
 *
 * 为什么两个函数都不返回错误码，出错直接 panic()：
 * 本 Lab 的磁盘是 QEMU 从一个必然存在的镜像文件模拟出来的，"读失败"
 * 在这个环境下只可能来自内核自己的 bug（算错了块号、驱动握手写错了
 * 寄存器顺序），不可能来自"磁盘坏了"这种真实内核必须优雅处理的情况。
 * 让这类 bug 立刻 panic 在出错的那一行，比让它沿着 fs_read -> sys_read
 * -> 用户程序一路变成一个静默的短读要好查得多。真实内核当然必须逐层
 * 上报 I/O 错误并重试，那套错误处理链条本身值得一整个 Lab，本课程不做。
 *
 * 为什么是同步阻塞、而且两个架构都用轮询而不用中断：
 * 中断驱动的磁盘 I/O 需要"当前进程睡下、等设备中断来了再唤醒"这一整套
 * 机制（睡眠队列 + 唤醒），而 Lab7 的调度器只有 RUNNABLE/RUNNING 两个
 * 活动状态，没有 SLEEPING。加上睡眠/唤醒是 Lab10 讨论并发时更自然的
 * 位置。轮询的代价是读盘期间这个 CPU 什么也干不了——在本 Lab 里读盘
 * 只发生在启动挂载和用户程序 read() 时，完全可以接受。
 */
#ifndef OSDEV_BLK_H
#define OSDEV_BLK_H

#include "types.h"

/* 探测并初始化块设备。找不到设备就 panic()——本 Lab 的内核没有"没有
 * 磁盘也能继续启动"这条路径（挂载不上文件系统之后也没有别的事可做），
 * 而且"忘了给 QEMU 加 -drive 参数"是这个 Lab 最常见的操作失误，让它
 * 在启动时就带着明确的提示停下来，比让它稍后在某次 blk_read 里读出
 * 一堆 0xFF、再表现为"魔数不匹配"要直接得多。 */
void blk_init(void);

/* 读第 blkno 个块（BSIZE 字节）到 buf。
 *
 * 本 Lab 里"文件系统的块"和"设备的扇区"都是 512 字节、一一对应，所以
 * 这里不需要做任何拆分或合并——blkno 直接就是扇区号/LBA。两者取一致的
 * 大小是有意的简化，见 fs_format.h 里 BSIZE 的注释。
 *
 * buf 必须至少有 BSIZE 字节。调用者都用栈上的局部数组（见 fs.c 里
 * 关于"为什么不用静态缓冲区"的说明）。 */
void blk_read(uint32_t blkno, void *buf);

#endif /* OSDEV_BLK_H */
