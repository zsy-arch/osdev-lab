/* Lab9：管道——本课程第一个"两个进程共享同一份可变内核状态"的对象。
 *
 * 一个管道就是内核里的一个字节缓冲区，加上两个端：写端把字节放进去，
 * 读端把字节取出来。两端各对应调用进程 fd 表里的一个表项，于是
 * `cat /motd.txt | grep lab` 这件事就变成了：shell 建一个管道，fork 两个
 * 孩子，让左边那个的 fd 1 指向写端、右边那个的 fd 0 指向读端，然后两个
 * 程序照常 write(1, ...) / read(0, ...)，谁都不知道自己在管道里。
 *
 * 这件"谁都不知道"是管道设计的全部精髓，也是 Unix 能把小程序拼成大工具
 * 的原因：grep 只会从 fd 0 读，它不关心 fd 0 背后是键盘、文件还是另一个
 * 进程的输出。把"连接关系"从程序里挪到 shell 里，是本 Lab 真正教的东西。
 *
 * ── 为什么这个文件比 fs.c 难 ──────────────────────────────────────
 *
 * 前面几个 Lab 里进程之间其实没有真正共享过任何*可变*的东西：
 *
 *   - fork() 是"全部复制"，父子从此各过各的；
 *   - 文件系统是只读的，两个进程读同一个 inode 互相看不见对方；
 *   - 连 fd 表也是 fork 时整个拷一份（见 proc.h 里 struct file 的注释）。
 *
 * 管道打破了这一点：它是可变的、共享的。两个后果随之而来，而它们正是
 * 本文件全部复杂度的来源：
 *
 *   1. **阻塞**。读一个空管道时，"没有数据"不是错误，是"还没到"——必须
 *      等。等就意味着当前进程要让出 CPU，而且醒来之后必须*重新检查*状态
 *      （因为期间别的进程改过它）。这是本课程第一次出现"一个系统调用中途
 *      让出 CPU、之后还要接着往下执行"。Lab7 的 sys_exit_proc() 也 swtch()
 *      出去过，但它永不返回，比这简单得多。
 *
 *   2. **生命周期**。管道本体不属于任何一个进程：写端的进程退出了，缓冲区
 *      里剩下的字节还得让读端读完；读端和写端都没了，这个管道才能回收。
 *      "还有几个 fd 指着我"必须被记下来，也就是引用计数。
 *
 * ── 引用计数为什么必须是计数、不能是布尔量 ────────────────────────
 *
 * xv6 把 readopen/writeopen 做成两个布尔量，因为它有一张全局的 struct file
 * 表，file 本身带引用计数，fork/dup 只是 f->ref++，真正的 pipeclose() 只在
 * 最后一个引用消失时被调用一次。
 *
 * 本 Lab 没有那张全局表（struct file 直接嵌在 PCB 里，见 proc.h 里的说明），
 * 所以 close() 会被调用*每个进程每个 fd 各一次*——sh 的管道流程里一共六次。
 * 布尔量在这里是错的：第一次 close 就会把写端标成"关闭"，而另一个进程手上
 * 那个写端还活着，读端于是提前看到 EOF，管道里的数据凭空丢掉一半。所以本
 * 文件用真正的计数：nread_open / nwrite_open，fork 和 dup 加，close 减。
 *
 * 这个名字跟 user/sh.c 注释里用的名字是同一个，不是巧合：sh.c 解释它那
 * 六个 close() 为什么一个都不能少时，讲的就是这两个计数的增减。两边的注释
 * 要能对上，读者才能把"用户程序为什么这样写"和"内核为什么这样实现"接起来。
 *
 * ── 为什么全文没有一把锁 ──────────────────────────────────────────
 *
 * 看过 xv6 pipe.c 的人第一反应会是"锁呢"。本文件确实没有锁，理由不是
 * "逻辑简单所以不需要"，而是一个具体的、可以指出来的性质：
 *
 *   系统调用在两个架构上都是关中断执行的。x86_64 靠 IA32_FMASK 在
 *   SYSCALL 时清掉 IF；riscv64 靠硬件在陷入 S 态时清掉 sstatus.SIE。
 *   所以定时器中断不可能打断一次系统调用，进程切换*只*发生在本文件
 *   显式调用 yield() 的那一刻。
 *
 * 于是每个函数从入口到第一个 yield()、以及两个 yield() 之间，都是不可分割
 * 的——效果等价于"整个函数持锁执行，只在 yield() 处放锁"。这正是 xv6 里
 * sleep() 所做的事（原子地放锁 + 睡下），只是本 Lab 因为单核 + 关中断，
 * 那个"原子"是免费的。
 *
 * 代价是这个性质很脆：一旦上多核，或者在管道操作中间打开中断，本文件
 * 立刻需要每个管道一把自旋锁。所以下面两个循环都写成"每次 yield() 回来
 * 重新读一遍共享状态"的形状——不是为了应付当下，是因为这才是正确的骨架，
 * 加锁时只需要在 yield() 前后插两行，不用重写逻辑。
 */
#ifndef OSDEV_PIPE_H
#define OSDEV_PIPE_H

#include "types.h"

/* 管道缓冲区大小。
 *
 * 512 的两个理由：
 *
 *   1. 它是 2 的幂，于是环形缓冲区的下标计算 `i % PIPEBUF` 编译成一条
 *      与运算，而不是一条除法。这是嵌入式代码里很常见的一个小选择。
 *
 *   2. 它正好是 POSIX 规定的 PIPE_BUF 下限。POSIX 保证"不超过 PIPE_BUF
 *      字节的 write 是原子的"——多个进程同时往一个管道写、每次不超过这个
 *      大小，各自的数据不会互相穿插。本 Lab 不实现那个保证（见下面
 *      pipe_write 的注释），但常量取成同一个值，读者查 POSIX 时能对上。
 *
 * 缓冲区大小的实际影响是"写端能领先读端多远"。太小则两个进程频繁互相
 * 等待（每次 yield 都是一次完整的调度往返）；太大则一个管道就吃掉可观的
 * 内存。Linux 默认是 64 KiB，xv6 是 512。 */
#define PIPEBUF 512

_Static_assert((PIPEBUF & (PIPEBUF - 1)) == 0,
               "PIPEBUF 必须是 2 的幂，否则下面的环形下标计算不成立");

/* 一个管道。
 *
 * 结构体本身就是这一课的主要内容，所以定义放在头文件里、而不是藏进
 * pipe.c——想知道"管道到底是什么"的人应该在这里就看到答案。（作为对比，
 * fs.h 刻意*不*暴露 inode 的内存布局，因为那一层的接口是 inode 号，
 * 布局是实现细节。这里不一样：struct pipe 的五个字段就是管道语义的全部。）
 *
 * ── nread / nwrite 为什么是单调递增的、而不是"头尾下标" ───────────
 *
 * 直觉的写法是存 head/tail 两个下标，在 [0, PIPEBUF) 里绕圈。问题是
 * head == tail 这一个状态同时表示"空"和"满"，得再加一个标志位或者永远
 * 浪费一个字节来区分。
 *
 * 单调计数没有这个歧义：nwrite 是"一共写进来过多少字节"，nread 是"一共
 * 读走过多少字节"，于是
 *
 *     当前有多少数据 = nwrite - nread      （0 表示空，PIPEBUF 表示满）
 *     下一个要写的位置 = nwrite % PIPEBUF
 *     下一个要读的位置 = nread  % PIPEBUF
 *
 * 三个量都由这两个数直接算出来，不存在"两个下标不一致"的中间状态。
 *
 * 溢出是安全的，而且理由值得想清楚：uint32_t 加到 0xFFFFFFFF 再加 1 会回到
 * 0（无符号溢出在 C 里是良定义的取模运算，不是未定义行为——有符号溢出才是）。
 * 回绕之后 nwrite < nread，但我们从来不比较这两个数的大小，只用它们的*差*。
 * 而无符号减法同样是取模运算，所以 nwrite - nread 在回绕前后都给出正确的
 * 占用量，只要真实占用量不超过 PIPEBUF——那是循环不变量，本文件保证它。
 * （这也是 Linux 内核 kfifo 用的同一个技巧。） */
struct pipe {
    /* 槽位是否在用。
     *
     * 用一个显式标志、而不是"两个计数都为 0 就算空闲"，是刻意的冗余：
     * 后者省一个字段，但一旦引用计数有 bug（少加了一次），一个还活着的
     * 管道会被当成空闲槽位重新分配给别人，症状是两个无关进程的数据串台,
     * 极难定位。有了 inuse，同样的 bug 表现为"管道泄漏"——pipe_alloc()
     * 最终返回 NULL，一眼就能看出问题在哪。
     *
     * 这是本课程反复出现的一个取舍：让错误的状态尽早变成*可观察的失败*,
     * 而不是变成"看起来还能跑"。 */
    int inuse;

    uint32_t nread;        /* 一共读走过多少字节（单调递增，允许回绕）。 */
    uint32_t nwrite;       /* 一共写进来过多少字节（同上）。 */

    /* 还有多少个 fd 指着读端 / 写端。都归零时这个管道被回收。 */
    uint32_t nread_open;
    uint32_t nwrite_open;

    char data[PIPEBUF];
};

/* 分配一个管道，两个计数都初始化成 1（调用者马上会把两端各放进一个 fd）。
 * 没有空闲槽位时返回 NULL——sys_pipe() 据此返回 -1，不 panic：管道用完是
 * 一个用户程序有可能触发、并且应该能收到错误的正常情况。 */
struct pipe *pipe_alloc(void);

/* 从管道读最多 n 字节，返回实际读到的字节数。
 *
 * 语义跟 POSIX read(2) 在管道上的行为一致，三种情况：
 *
 *   - 有数据：立刻返回，可能*少于* n。这个"可能少于"是必须的，不是优化：
 *     如果非要凑满 n 才返回，`cat /motd.txt | grep lab` 里的 grep 一旦
 *     请求的字节数超过管道里的总数据量就会永远等下去（cat 已经退出了,
 *     不会再有人写）。管道上的 read 语义是"给我现在有的"。
 *
 *   - 空的、但写端还在：阻塞（yield 直到有数据或者写端全关）。
 *
 *   - 空的、且写端全关：返回 0，也就是 EOF。注意顺序——先看有没有数据,
 *     再看写端在不在。写端退出后缓冲区里剩的字节必须先交付完，否则
 *     `echo hi | cat` 会丢数据（echo 通常在 cat 第一次 read 之前就退出了）。 */
int pipe_read(struct pipe *pi, char *dst, uint32_t n);

/* 往管道写 n 字节。成功返回 n，读端已全关时返回 -1。
 *
 * 满了就阻塞，直到 n 个字节*全部*写进去才返回——不做"短写"。POSIX 允许
 * 短写（返回小于 n 的正数），但本 Lab 的用户库不处理：ulib 的 fputs() 发
 * 一次 write 就完事、不看返回值，短写会让程序输出被静默截断，而这种 bug
 * 表现为"输出少了几个字符"，学生几乎不可能想到是内核的锅。让内核在这里
 * 多承担一点，是为了让用户程序那边的错误模式保持简单。 */
int pipe_write(struct pipe *pi, const char *src, uint32_t n);

/* 关闭管道的一端：writable 非 0 关写端，为 0 关读端。
 *
 * 只减对应的那个计数；两个都归零时释放槽位。这个函数不碰 fd 表——调用者
 * （sys_close / sys_exit_proc）负责把自己那个表项清成 FD_NONE。 */
void pipe_close(struct pipe *pi, int writable);

/* 多了一个 fd 指向这一端：writable 非 0 是写端，为 0 是读端。
 *
 * 两个调用点：sys_dup（显式复制一个 fd）和 sys_fork（子进程继承了父进程
 * 整张 fd 表）。fork 那边容易漏——struct proc 的结构体赋值会把 pipe 指针
 * 一起拷过去，代码看着"已经对了"，但计数没加，于是子进程一 close 就把
 * 计数减成 0，父进程手上那一端突然失效。proc.c 里 fork 的 fd 表拷贝那段
 * 有对应的注释。 */
void pipe_dup(struct pipe *pi, int writable);

#endif /* OSDEV_PIPE_H */
