/* Lab9：系统调用号约定。
 *
 * 这个文件在 Lab6/7/8 里是*每个架构目录下各放一份*的，Lab9 把它挪到了
 * Lab 根目录，跟 fs_format.h 并列。这次搬迁本身就是本 Lab 的一个教学点,
 * 值得把前因后果写清楚。
 *
 * Lab6 当时的理由（原文保留在下面）是：syscall.h 只是一份"调用号数值"的
 * 约定，而 syscall 的*实现*两个架构完全不同（syscall/sysret vs ecall/
 * sret、参数寄存器不同），为了不在 src/common 里放一个"其实只被两个几乎
 * 独立的实现各自 include 一份"的文件，就在两边各放一份相同的内容。
 *
 * 那个判断在当时是对的：只有两个使用者，而且都在内核里。Lab9 变了两件事:
 *
 *   1. 使用者从 2 个变成 4 个：两个内核，加上 user/ 下的用户程序——而
 *      user/ 是跨架构共享的一份源码，它没有"两个架构各一份"的位置可放。
 *   2. 性质从"内核内部约定"变成"内核与用户程序之间的契约"。系统调用号
 *      是一条 ABI：内核按这个号分发，用户程序按这个号发起。两边对不上,
 *      症状是用户程序调 write 却执行了内核的 exec——不会有任何编译错误。
 *
 * 第 2 点才是决定性的。跨越特权级边界的约定必须只有一处定义，这跟
 * fs_format.h 里"磁盘格式只能有一份"是同一条原则的另一个方向：一个跨越
 * *时间*（写镜像的 mkfs 和读镜像的内核不同时运行），一个跨越*特权级*。
 * 真实系统把这类定义集中在 UAPI 头文件里（Linux 的
 * include/uapi/asm-generic/unistd.h），正是同一个考虑。
 *
 * 所以 Lab6 的做法不是错，是它的前提到 Lab9 失效了。"当时的判断依据"
 * 比"当时的结论"重要得多——依据写下来了，前提变了就能看出该改；只写
 * 结论的话，这个文件会在两个架构目录下一直躺着，然后有人给用户程序拷
 * 出第三份。
 *
 * -- 以下是 Lab6~Lab8 的号段说明，原样保留 --
 *
 * Lab6 定义两个号：sys_write 是 ROADMAP 明确要求的"最小系统调用"，
 * sys_exit 是让用户程序能够主动结束执行、把控制权交还内核。
 *
 * Lab7 新增三个号：fork/exec/wait，是"进程"这个抽象真正需要的最小系统
 * 调用集合。
 *
 * Lab8 新增三个号：open/read/close，建立*文件描述符*这个抽象：用一个
 * 不透明的小整数代表内核里的一份状态。当时的注释预告了两件事，现在都
 * 到期了：
 *
 *   "后面 Lab9 的 shell 重定向、Lab10 的管道全都建立在它上面"
 *   —— 管道提前到了本 Lab（见 SYS_PIPE），因为没有管道的 shell 缺了
 *      最能说明 fd 抽象威力的那一半。
 *
 *   "注意 SYS_READ 和已有的 SYS_WRITE 现在是不对称的：write 只认 fd 1
 *    （控制台），read 只认 open() 返回的文件 fd。真正的 Unix 里两者是
 *    完全对称的……把控制台也做成 fd 表里的一项是本 Lab 的挑战任务之一"
 *   —— 本 Lab 把这条挑战任务做成了正式内容。理由见下面 SYS_DUP 的注释:
 *      没有"控制台也是 fd 表里的一项"，重定向和管道就没有落脚的地方。
 */
#ifndef OSDEV_SYSCALL_H
#define OSDEV_SYSCALL_H

#define SYS_WRITE 1
#define SYS_EXIT  2
#define SYS_FORK  3
#define SYS_EXEC  4
#define SYS_WAIT  5
#define SYS_OPEN  6
#define SYS_READ  7
#define SYS_CLOSE 8

/* Lab9 新增两个号。
 *
 * SYS_PIPE：创建一对相连的 fd，写进 fd[1] 的字节能从 fd[0] 读出来。
 * 这是 Unix 里最小的进程间通信原语，也是 shell 里 `a | b` 的全部机制。
 *
 * SYS_DUP：复制一个 fd 到当前进程最小的空闲 fd 号上。
 *
 * 为什么有了 pipe 还需要 dup——这是本 Lab 最值得想明白的一处设计。
 * shell 要实现 `cat f | grep x`，需要让 cat 的"标准输出"变成管道的写端。
 * 但 cat 这个程序里写的是 write(1, ...)，它不知道管道的存在，也不应该
 * 知道。所以必须由 shell 在 fork 之后、exec 之前，把子进程的 fd 1 换成
 * 管道写端：
 *
 *     close(1);        // fd 1 空出来
 *     dup(pipe_wfd);   // 复制到最小空闲 fd —— 正好是刚空出来的 1
 *     close(pipe_wfd); // 原来那个号不需要了
 *
 * 这套"close 腾位置 + dup 补上去"的手法依赖一条很关键的语义：dup 必须
 * 返回*最小*的空闲 fd，而不是随便一个。这不是实现细节，是 POSIX 明文
 * 规定的行为，正因为 shell 这样用它。（真实系统还有 dup2(old, new) 可以
 * 指定目标号，就不必依赖"最小"这个性质了；dup2 是更晚加进来的，而本 Lab
 * 刻意只做 dup，为的就是让这条依赖显式暴露出来。）
 *
 * 整件事成立的前提是"fd 1 是 fd 表里一个普通的项，可以被关掉和替换"。
 * Lab8 的 sys_write 里 fd 1 是一个写死的常量（if (fd != 1) 就报错），
 * 那种实现下重定向无从下手——你没法"关掉"一个常量。所以本 Lab 必须先把
 * 控制台变成 fd 表里的一项（Lab8 留下的挑战任务），重定向和管道才有
 * 落脚点。这是一个很典型的例子：一个看起来只是"更整齐"的抽象改动，
 * 实际上是后面一整类功能的前提条件。 */
#define SYS_PIPE  9
#define SYS_DUP   10

#endif /* OSDEV_SYSCALL_H */
