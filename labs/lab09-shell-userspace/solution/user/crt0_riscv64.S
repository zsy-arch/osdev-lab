/* Lab9：riscv64 用户程序启动代码。
 *
 * 跟 crt0_x86_64.S 完全对应：从栈顶取 argc/argv，call main，把返回值交给
 * exit。内核构造的栈布局两个架构一模一样（那是内核 exec.c 里跟架构无关的
 * 一段代码），差异全在"怎么把栈上的两个值变成本架构的 C 参数"。
 *
 * 逐条对照 x86_64
 * --------------
 *   取 argc：  movq (%rsp), %rdi     →   ld a0, 0(sp)
 *   取 argv：  leaq 8(%rsp), %rsi    →   addi a1, sp, 8
 *
 *   x86_64 的 lea 是"算地址但不访存"的专用指令；RISC-V 没有这种指令，
 *   因为它根本不需要——地址计算就是普通的整数加法，addi 本来就是加法。
 *   x86_64 需要 lea 是因为它的 mov 带一套复杂的内存寻址语法
 *   （base + index*scale + disp），lea 的作用是"把寻址语法当算术用"。
 *   RISC-V 的 load/store 只有 reg+imm 一种寻址方式，算术和访存从语法上
 *   就分开了，所以不存在对应的指令，也不存在"lea 还是 mov"这个选择题。
 *
 *   栈对齐：   什么都不做（但理由不同，见下）
 *   调用 main：call main            →   call main（伪指令，展开成 auipc+jalr）
 *   传退出码： movl %eax, %edi      →   mv a0, a0  ——即什么都不用做
 *
 *   最后一条是个小惊喜：RISC-V 的返回值寄存器和第一个参数寄存器是同一个
 *   （a0）。所以"把 main 的返回值作为 exit 的第一个参数"这件事，在
 *   x86_64 上要一条 mov（返回值在 eax，参数要在 edi），在 riscv64 上是
 *   零条指令。
 *
 *   这个设计不是偶然：RISC-V 刻意让 a0/a1 兼任"前两个参数"和"前两个返回
 *   值"，正是为了让这种转发模式免费。代价是编译器少了两个可以随便用的
 *   寄存器名，但 RISC-V 有 32 个寄存器，不缺。
 */

.section .text

.globl _start
.type _start, @function
_start:
    /* argc 在栈顶（内核压进去的是 64 位值，main 的 argc 是 int，高位是 0）。 */
    ld   a0, 0(sp)              /* 第 1 个参数：argc */
    addi a1, sp, 8              /* 第 2 个参数：argv（指针数组首地址） */

    /* 栈对齐：RISC-V 的 ABI 要求 sp 始终保持 16 字节对齐——注意是"始终"，
     * 不是"call 的那一刻"。
     *
     * 这跟 x86_64 差一个返回地址的原因很直接：RISC-V 的 call（jal）把
     * 返回地址写进 ra 寄存器，不动 sp。所以 sp 的对齐状态穿过函数调用
     * 边界时不变，"入口处对齐"和"调用点对齐"是同一件事。
     *
     * 于是这里跟 x86_64 一样什么都不用做，但不需要解释"为什么差 8"——
     * 这个架构上不存在那个差值。x86_64 那边之所以要专门写一大段说明,
     * 就是因为 push 返回地址这个动作把 ABI 的规定和观察到的现象错开了。
     *
     * 一个副作用：RISC-V 上函数序言里不会出现"为了对齐而调整 sp"的指令,
     * 只会出现"为了腾出局部变量空间"的调整，而且那个调整量本身就是 16 的
     * 倍数。看反汇编时这一点让 riscv64 的栈帧比 x86_64 好读。 */

    /* gp（global pointer）寄存器：我们故意*不*初始化它。
     *
     * 真实的 riscv64 crt0 会有这么两行：
     *
     *     .option push
     *     .option norelax
     *     la gp, __global_pointer$
     *     .option pop
     *
     * 作用是让 gp 指向 .sdata/.sbss 的中间，之后所有小全局变量都能用
     * "gp + 12 位偏移"一条指令访问，省掉 auipc。链接器的 relaxation 会
     * 把符合条件的 auipc+addi 对自动改写成 gp 相对寻址——注意那对
     * .option norelax：这一段自己不能被 relax，否则就成了"用还没设好的
     * gp 去加载 gp"。
     *
     * 我们不做，有两个理由：
     *
     *   1. relaxation 只在链接器看到 __global_pointer$ 这个符号有定义时
     *      才会启动。我们的 user.ld 没有定义它（内核的 linker.ld 也没有,
     *      见 solution/riscv64/linker.ld），所以编译器生成的是绝对寻址,
     *      gp 里放什么都不会被用到。少一个必须正确初始化才不出错的
     *      全局状态。
     *
     *   2. 这是本课程一贯的取舍：省一条指令换一个"忘了初始化就静默错位"
     *      的隐患，不值得。gp 出错的症状是"某几个全局变量读到垃圾，另外
     *      几个正常"——取决于编译器把哪些变量放进了 .sdata。极难查。
     *
     * .sdata/.sbss 这两个段名仍然必须写在 user.ld 里。这点容易混淆：
     * 不用 gp 寻址，不代表编译器不往这两个段里放东西——它照样放（这是
     * 段分配策略，跟寻址方式是两回事），只是访问时用绝对地址。段名漏了
     * 的话变量会错位，这是本课程实测踩过的坑。 */

    call main

    /* main 的返回值已经在 a0 里，正好是 exit 的第一个参数位置。 */
    call exit

    /* exit 不该返回。万一返回了，用一条保证会陷入的指令立刻崩掉，而不是
     * 让 CPU 溜到 .text 里下一个函数的字节上去。
     *
     * x86_64 那边用 hlt（用户态执行触发 #GP）。RISC-V 没有"用户态一定
     * 非法"的简单指令可用：wfi 在 U 模式下的行为由 mstatus.TW 决定，不
     * 一定陷入；ecall 会变成一次系统调用号未定义的调用，内核会返回 -1
     * 然后继续往下走，反而更糟。
     *
     * unimp 是专门为这个用途存在的伪指令：它展开成一个保证未定义的编码
     * （C 扩展下是 16 位的 0x0000，否则是 32 位的 0xC0001073），执行到
     * 就产生非法指令异常。名字也直说了意图——"这里不该被执行到"。
     *
     * 内核的 panic 输出会打出 scause=2（Illegal instruction）和出错的
     * sepc，而 sepc 落在 crt0 里，一眼就能定位。 */
    unimp
    .size _start, . - _start

.section .note.GNU-stack, "", @progbits
