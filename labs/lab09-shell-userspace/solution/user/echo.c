/* Lab9：echo —— 把参数打回标准输出。
 *
 * 这是六个用户程序里最小的一个，作用是把"argv 确实传到了"这件事变成可以
 * 被自动化测试观察到的输出。真实的 echo 也基本就是这样（GNU coreutils 的
 * echo.c 多出来的部分全是 -n/-e 选项和转义序列处理）。
 *
 * 值得注意的是参数之间的空格：echo a b c 输出 "a b c\n"，即空格只出现在
 * 参数*之间*，不在末尾。这个细节决定了循环的写法——不能每个参数后面都跟
 * 一个空格，那样会输出 "a b c \n"。
 *
 * 对照 shell 的解析：echo 收到的是已经切分好的 argv 数组，它看不到用户
 * 原本输入的那一行里有几个空格。`echo  a   b` 和 `echo a b` 对 echo 来说
 * 完全一样，因为切分发生在 sh.c 里。这就是为什么 Unix 里 echo 不能保留
 * 原始空白——信息在进入程序之前就丢掉了。想保留就得加引号，而引号的处理
 * 同样在 shell 里（本 Lab 的 sh 不支持引号，见 sh.c 的说明）。
 */
#include "user.h"

int main(int argc, char **argv)
{
    /* 从 1 开始：argv[0] 是程序名（"echo"），不该被打印出来。
     *
     * argv[0] 的存在本身是个约定而不是必然——内核完全可以只传真正的参数。
     * 保留它是因为程序常常需要知道自己是用什么名字被调用的：busybox 就
     * 靠 argv[0] 判断自己该表现成 ls 还是 cat（一个二进制配上多个符号
     * 链接）。我们的 exec 也照这个约定传（见 exec.c）。 */
    for (int i = 1; i < argc; i++) {
        puts(argv[i]);
        /* 空格只加在参数之间：最后一个参数后面不加。 */
        if (i < argc - 1) {
            puts(" ");
        }
    }
    puts("\n");
    return 0;
}
