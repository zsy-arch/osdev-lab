/* Lab9：x86_64 用户程序启动代码（C runtime, 第 0 号）。
 *
 * ELF 加载器把控制权交给 e_entry 指向的地址时，我们还不在 C 的世界里：
 * 没有 argc/argv 参数寄存器，main 返回之后也没有地方可去。这个文件就是
 * 那段"从裸入口点到 main()"的胶水，真实系统上它来自 libc 提供的 crt1.o
 * （历史上叫 crt0.o，名字沿用至今）。
 *
 * 一共只做三件事：
 *   1. 从用户栈上取出 argc 和 argv，放进 C 调用约定的前两个参数寄存器。
 *   2. call main。
 *   3. 把 main 的返回值当退出码，call exit。
 *
 * 真实 crt1.o 还做什么（我们全都不做，列在这里是为了知道被省掉了什么）
 * ------------------------------------------------------------------
 *   - 初始化 TLS（线程局部存储）和设置 fs 段基址——我们没有线程。
 *   - 初始化栈保护的 canary 值——我们用 -fno-stack-protector 关掉了。
 *   - 调用 .init_array 里的构造函数（C++ 全局对象、__attribute__((constructor))
 *     标记的函数）——我们的链接脚本连 .init_array 都没列，因为没人用。
 *   - 注册 atexit 处理链、刷新 stdio 缓冲区——我们的 write 直接是系统调用,
 *     没有缓冲区要刷。
 *   - 把 envp（环境变量）和 auxv（内核传给程序的辅助信息：页大小、
 *     入口点、随机数种子……）也解析出来——我们不支持环境变量。
 *
 * 少掉这些之后剩下的这十来条指令，就是"运行一个 C 程序"真正不可省略的
 * 部分。值得记住这个比例：libc 启动路径上绝大多数代码服务的是我们暂时
 * 不需要的特性，而不是 C 语言本身。
 */

.section .text

/* 内核（exec.c）在跳转前把用户栈布置成这样——这是 System V ABI 规定的
 * 进程初始栈布局，我们照抄它，不是为了兼容什么，是因为它确实是最直接的
 * 安排，而且照抄能让 GDB 那些懂 ABI 的命令直接用上：
 *
 *      高地址
 *                  ┌──────────────────┐ ← USER_STACK_VADDR + 页大小
 *                  │ "grep\0" ...     │  argv 字符串本体
 *                  │ "hello\0"        │
 *                  ├──────────────────┤  （按 8 字节对齐）
 *                  │ NULL             │  argv[argc]，结束标记
 *                  │ &"hello"         │  argv[1]
 *                  │ &"grep"          │  argv[0]
 *                  ├──────────────────┤ ← argv 指向这里
 *                  │ argc             │ ← 入口时 %rsp 指向这里
 *                  └──────────────────┘
 *      低地址
 *
 * 为什么 argc 放在栈上而不是放在寄存器里传进来（内核完全可以在 exec 时
 * 直接把 rdi/rsi 设好，省掉这个文件）：
 *
 *   1. argv 的字符串本体无论如何都得在用户栈上——内核那份 path/argv 位于
 *      内核地址空间，用户程序访问不到，必须拷进新地址空间。既然字符串
 *      已经在栈上了，指针数组顺手也放栈上，布局是连续的一整块。
 *   2. 寄存器传参会让"内核知道 C 调用约定"。现在内核只需要知道"栈顶那一
 *      块字节长什么样"，crt0 负责把它翻译成本架构的 C 约定——两个架构的
 *      crt0 不同，而内核那段构造栈的代码可以完全一样（见 exec.c 里
 *      user_stack_build 的注释）。
 *   3. 这就是真实系统的做法。execve 之后 %rdi 的值是未定义的；Linux 只
 *      保证栈顶布局。
 */
.globl _start
.type _start, @function
_start:
    /* argc 在栈顶。注意这里用 movq 读的是一个 64 位值——内核压进去的就是
     * 64 位，虽然 main 的 argc 参数是 int（32 位）。高 32 位是 0，传给
     * main 时编译器只看 %edi，没有问题。 */
    movq (%rsp), %rdi           /* 第 1 个参数：argc */

    /* argv 是紧挨着 argc 上面那个指针数组的首地址。用 lea 算地址而不是
     * movq 读值——argv 不是一个存在栈上的指针，它*就是*那块栈空间的地址。
     * 这是 lea 和 mov 最典型的区别场合。 */
    leaq 8(%rsp), %rsi          /* 第 2 个参数：argv */

    /* 栈对齐。
     *
     * System V AMD64 ABI 要求：在 call 指令执行的那一刻，%rsp 必须是
     * 16 的倍数。这条规则存在是因为 SSE 指令（movaps 等）要求 16 字节
     * 对齐的内存操作数，而编译器会假设 ABI 被遵守了，直接对栈上的局部
     * 变量用对齐版本的指令。
     *
     * 我们不用 SSE（-mgeneral-regs-only），所以违反这条规则大概不会当场
     * 出错。但"大概不会"是最糟糕的状态：等哪天某个函数里出现一次结构体
     * 赋值、编译器选了 movaps，程序就在一个跟栈对齐毫无关系的地方崩掉。
     * 所以还是对齐好。
     *
     * 那么这里需要做什么？什么都不需要——但理由值得说清楚，因为这是
     * x86_64 栈对齐最容易搞反的一处：
     *
     *   - 内核构造栈时保证入口处 %rsp % 16 == 0（见 exec.c）。
     *   - 下面的 `call main` 会先 push 8 字节返回地址，所以 main 的第一条
     *     指令执行时 %rsp % 16 == 8。
     *
     * 也就是说，"call 之前 16 对齐" 等价于 "被调函数入口处偏移 8"。ABI
     * 说的是前者，而人们看到的现象是后者，两者差一个返回地址——把这两句
     * 话搞混，就会在这里画蛇添足加一条 subq $8, %rsp，反而破坏了对齐。
     *
     * 编译器生成的每个函数序言都在维护这个不变量（这也是为什么函数里常
     * 见 sub $0x8 这种看起来多余的调整）。crt0 是这条链子的第一环，它
     * 只要不打破从内核继承来的对齐就行。
     *
     * 对照 riscv64：那边入口和函数内都是 sp % 16 == 0，没有这个差 8 的
     * 现象，因为返回地址在 ra 寄存器里而不是压栈。 */

    call main

    /* main 返回了。返回值在 %eax 里，按 C 约定；把它当退出码传给 exit。
     *
     * 为什么 main 可以 return 而不必显式调用 exit：因为有这两条指令。
     * C 标准规定 main 的 return 等价于 exit(返回值)，而这个等价关系不是
     * 语言魔法，就是启动代码里的一次转发。
     *
     * 我们的 main 大多写成 int main(void)，没有 return 语句——C 里 main
     * 是唯一"落到函数末尾"等价于 return 0 的函数。编译器会生成 xor %eax,
     * %eax，所以下面拿到的是 0。 */
    movl %eax, %edi
    call exit

    /* exit 不返回（sys_exit 不会回到用户态）。但万一它返回了，下面这条
     * 指令必须存在，否则 CPU 会继续执行 .text 段里紧跟着的下一个函数的
     * 字节——那会变成一次莫名其妙的"程序跑到另一个函数里去了"。
     *
     * hlt 在用户态（CPL=3）执行会产生 #GP 通用保护异常。这正是想要的
     * 效果：立刻、明确地崩掉，而且崩溃地址就在 crt0 里，一眼能看出是
     * "exit 居然返回了"。用一个死循环（jmp .）则会让程序静静地挂住，
     * 症状是测试超时，排查起来要多花好几步。
     *
     * 选一个"出错就响"的失败方式，比选一个"出错就静"的，在系统编程里
     * 几乎总是更好。 */
    hlt
    .size _start, . - _start

.section .note.GNU-stack, "", @progbits
