/* Lab9：ls —— 列出根目录里的文件。
 *
 * 这个程序的实现方式是本 Lab 最值得停下来看一眼的地方，因为它*没有*用
 * 任何目录专用的系统调用：
 *
 *     int fd = open(".");                    // 就是普通的 open
 *     read(fd, &de, sizeof(de));             // 就是普通的 read
 *
 * 目录在 Unix 文件系统里是一个"内容恰好是 dirent 数组"的普通文件。它的
 * inode 跟普通文件的 inode 是同一种结构（只有 type 字段不同），占用数据
 * 块的方式一样，读它走的是同一条 fs_read 路径。所以"列目录"不需要新的
 * 机制，只需要按正确的结构去解释读出来的字节。
 *
 * 这个统一带来的直接好处是：本 Lab 实现 ls 时，内核侧一行都不用改。
 *
 * 那为什么真实系统有 getdents(2) 而不让用户直接 read 目录
 * ----------------------------------------------------
 * 因为"目录的字节布局"是文件系统的内部格式。ext4 的目录项是变长的、带
 * 哈希树索引；btrfs 的目录项存在 B 树里，根本不存在"目录文件的第 N 个
 * 字节"这种东西。让用户程序直接 read 目录，等于把每一种文件系统的磁盘
 * 格式都变成公开 ABI——一旦有程序依赖它，格式就再也不能改了。
 *
 * 所以现代 Unix 上 read(2) 一个目录 fd 直接返回 EISDIR，必须走 getdents,
 * 由内核把内部格式翻译成统一的 struct linux_dirent。这是一层刻意加进来
 * 的抽象，代价是多一个系统调用，换来的是文件系统格式可以自由演进。
 *
 * 我们这里直接 read，理由是：本 Lab 只有一种文件系统、格式定义
 * （fs_format.h）本来就是内核和用户程序共享的一份文件，那层翻译没有任何
 * 东西可翻译。但要知道我们省掉的是什么——"用户程序能看懂磁盘格式"在
 * 教学系统里是省事，在真实系统里是设计错误。（把 ls 改成走一个新增的
 * sys_getdents 是本 Lab 的挑战任务之一。）
 *
 * 顺带一个语言细节：ls 能 include fs_format.h，靠的是 Makefile 给用户
 * 程序加的 -I$(LAB_ROOT)。那个目录里只有 fs_format.h / syscall.h / elf.h
 * 这类描述*外部约定*的头文件，没有任何内核内部接口——见 user/types.h
 * 开头关于"用头文件可见性划特权级边界"的说明。
 */
#include "user.h"
#include "fs_format.h"

int main(int argc, char **argv)
{
    /* 允许 `ls` 和 `ls /` 两种写法，其它参数一律当成目录名传给 open。
     *
     * 我们的文件系统是扁平的（只有根目录，见 fs.h 里 fs_lookup 的说明），
     * 所以"目录名"实际上只有 "."、"/"、"" 三种等价写法有意义。传别的
     * 名字进去会打开一个普通文件，然后把它的内容当 dirent 数组解释——
     * 输出是乱码。真实的 ls 会先 stat 一下确认这是目录，我们没有 stat
     * （只读文件系统里 stat 的大部分字段都没意义），所以这里只能靠
     * "别那么用"。这是本 Lab 已知的粗糙之处，写在这里而不是假装没有。 */
    const char *path = (argc > 1) ? argv[1] : ".";

    int fd = open(path);
    if (fd < 0) {
        fputs(2, "ls: cannot open ");
        fputs(2, path);
        fputs(2, "\n");
        return 1;
    }

    /* 一次读一个 dirent（32 字节），而不是读一整块再遍历。
     *
     * 一次读一项在效率上是差的选择——32 个字节一次系统调用，每次都要走
     * 完整的陷入/返回路径，而且内核那边每次 fs_read 还要重读一次 inode
     * 块（见 fs.c 里的说明）。真实的 ls 会读几 KiB 再解析。
     *
     * 选它是因为它让"目录 = dirent 数组"这件事在代码里直接看得见：读多少
     * 字节就是 sizeof(struct dirent)，循环一次就是一项。一旦改成读整块,
     * 就要多出"块内偏移"、"跨块的项怎么办"这些簿记，而那些簿记跟本 Lab
     * 想讲的东西无关。
     *
     * 一个附带的正确性好处：我们的 dirent 是 32 字节、BSIZE 是 512，整除
     * （fs_format.h 里有 _Static_assert 保证），所以 dirent 永远不跨块。
     * 但那是*内核*可以依赖的性质；用户程序看到的是一个字节流，它没理由
     * 知道块大小。一次读一项的写法对块大小完全不敏感，这是它除了清晰
     * 之外的另一个优点。 */
    struct dirent de;
    int n;

    while ((n = read(fd, &de, sizeof(de))) == (int)sizeof(de)) {
        /* inum == 0 是空目录项——文件被删除后留下的洞。我们的 mkfs 不
         * 产生这种项（镜像是一次性生成的，没有删除操作），但格式允许,
         * 所以要跳过。
         *
         * 这一行是"按格式的规定写，而不是按当前镜像的实际情况写"的例子。
         * 省掉它，今天的测试一样通过；哪天加了 unlink，ls 就开始输出
         * 空名字和残留名字，而且那个 bug 看起来跟 unlink 的实现有关,
         * 不会有人怀疑 ls。 */
        if (de.inum == 0) {
            continue;
        }

        /* 名字可能没有 '\0' 结尾。
         *
         * fs_format.h 说得很明确：name 是 char[DIRSIZ]，正好 DIRSIZ(30)
         * 个字符的名字会占满整个字段，不留终止符的位置。直接 puts(de.name)
         * 在那种情况下会一路读到下一个字段（inum）甚至越过 de 变量本身,
         * 打出一串垃圾。
         *
         * 定长不带终止符的字符串字段在磁盘格式和网络协议里非常常见
         * （省一个字节、字段大小固定），代价就是每个读取方都必须自己处理
         * 这件事。我们的做法是拷进一个大一号的缓冲区再补上终止符：
         *
         *   - 缓冲区声明成 DIRSIZ + 1，那个 +1 就是终止符的位置。
         *   - memcpy 固定拷 DIRSIZ 个字节（不能用 strlen 求长度——名字
         *     可能没有终止符，strlen 会越界）。
         *   - 然后把第 DIRSIZ 个字节（下标从 0 数，就是缓冲区最后一格）
         *     写成 '\0'。
         *
         * 注意补 '\0' 的位置是固定的 DIRSIZ，不是 "名字的实际长度"。名字
         * 短于 DIRSIZ 时字段里本来就有 '\0'，puts 会在那里停下；名字正好
         * 占满时靠我们补的这个停下。两种情况一套代码。 */
        char name[DIRSIZ + 1];
        memcpy(name, de.name, DIRSIZ);
        name[DIRSIZ] = '\0';

        puts(name);
        puts("\n");
    }

    /* 循环退出的三种可能，分开处理：
     *
     *   n == 0                  正常读完（EOF）
     *   n < 0                   read 出错
     *   0 < n < sizeof(de)      短读——目录大小不是 dirent 的整数倍
     *
     * 第三种在我们的系统里不可能发生（内核的 fs_lookup 里有一个 panic
     * 专门拦它），但用户程序不该假设内核是对的。把它跟 EOF 混在一起
     * （比如写成 while (read(...) > 0)）会让这种损坏静默通过，最后表现
     * 成"ls 少列了一个文件"——那是最糟的一类症状，因为输出看起来完全
     * 正常。 */
    if (n < 0) {
        fputs(2, "ls: read error\n");
        close(fd);
        return 1;
    }
    if (n != 0) {
        fputs(2, "ls: corrupt directory (partial dirent)\n");
        close(fd);
        return 1;
    }

    close(fd);
    return 0;
}
