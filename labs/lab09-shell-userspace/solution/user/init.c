/* Lab9：init —— 第一个用户进程。
 *
 * 内核启动的最后一步是创建这个进程（见 kernel_main.c）。它是唯一一个
 * 不是由 fork 产生的用户进程，所以它的 pid 是 1，所有其它用户进程都是
 * 它的后代。
 *
 * init 在真实系统里的职责很多（挂载文件系统、启动服务、收养孤儿进程、
 * 处理关机），本 Lab 只保留两件：
 *
 *   1. 跑一遍启动脚本 /initrc，把本 Lab 要演示的东西全部执行一次。
 *   2. 之后进入一个"启动 shell、等它结束、再启动一个"的无限循环。
 *
 * 第 2 点是 init 不可省略的那部分职责。考虑一下如果 init 在跑完脚本后
 * 直接 exit 会怎样：pid 1 退出了，而它的子进程（shell）如果还在，就成了
 * 孤儿——在我们的内核里没有"收养"机制，那些进程的退出状态永远没人回收,
 * 进程表会慢慢被占满。真实 Unix 内核会把孤儿进程重新挂到 pid 1 底下,
 * 正是因为 init 被假定永不退出。
 *
 * 更直接的理由：init 退出之后系统就没有任何用户进程了，内核的调度器会
 * 空转。那不是崩溃，但也不是一个能用的系统——开机、跑完、然后什么都不
 * 能做。"永不退出的 pid 1"是"系统一直可用"的最低要求。
 *
 * 为什么不让 init 自己变成 shell（exec 掉自己）
 * -------------------------------------------
 * 那样更省一个进程，而且看起来很自然。不行，因为 shell 会退出（用户按
 * Ctrl-D、脚本读到 EOF），而 init 不能退出——上面刚说过原因。init 必须
 * 保持存在，才能在 shell 死掉之后再启动一个。
 *
 * 这个"父进程守着、子进程可以死"的结构是 Unix 里最基础的进程管理模式,
 * 而它需要的全部机制就是 fork + wait。systemd 那样的现代 init 做的事情
 * 多得多，但最核心的那个循环仍然是这个形状。
 */
#include "user.h"

int main(void)
{
    /* ---- 第一阶段：跑启动脚本 ---- */

    /* fork 出一个子进程去跑 `sh /initrc`。
     *
     * 为什么要 fork 而不是直接 exec：exec 会把 init 自己替换成 sh，脚本
     * 跑完 sh 退出，就没有 pid 1 了。见上面的说明。 */
    int pid = fork();
    if (pid < 0) {
        fputs(2, "init: fork failed\n");
        exit(1);
    }
    if (pid == 0) {
        /* 子进程：变成 sh，参数是脚本路径。
         *
         * argv 数组必须以 NULL 结尾，而且 argv[0] 按惯例是程序名。sh 会
         * 检查 argc > 1 来决定进脚本模式（见 sh.c 的 main）。 */
        char *sh_argv[] = { "sh", "/initrc", NULL };
        exec("/sh", sh_argv);

        /* 只有 exec 失败才会走到这里。 */
        fputs(2, "init: exec /sh failed\n");
        exit(1);
    }

    /* 父进程等脚本跑完。
     *
     * 这个 wait 是本 Lab 第一个真正会*阻塞*的系统调用：脚本里有六条命令,
     * 每条都要 fork/exec/wait，全部跑完需要很多次调度。Lab8 的 sys_wait
     * 是非阻塞的（没有子进程结束就直接返回 -1），那种实现下这一行会立刻
     * 返回，init 紧接着打印下面的标记，而脚本的输出会混在标记后面——输出
     * 顺序不确定，测试没法比对。
     *
     * 所以"让 wait 阻塞"不是锦上添花，是本 Lab 能被测试的前提。它也是
     * 本 Lab 对内核改动最大的一处：一个系统调用要能中途让出 CPU、之后
     * 再恢复执行，而 Lab7/Lab8 的陷入代码里有三个全局变量假定了"系统
     * 调用不会中途切换"（见 README 的常见坑一节）。 */
    wait();

    /* ---- 标记：脚本阶段结束 ---- */

    /* 这一行是自动化测试的锚点。
     *
     * 测试脚本（scripts/test-lab.sh）按行比对输出，它需要一个"到这里
     * 为止该出现的东西都出现了"的标志。没有这个标记的话，测试只能检查
     * 各条命令的输出都在，但检查不出它们是否在正确的时刻出现——比如
     * 如果 wait 没阻塞，标记会出现在脚本输出的中间，比对就会失败。
     *
     * 换句话说：这一行把"顺序正确"变成了一个可以用 grep 检查的性质。 */
    puts("init: initrc finished\n");

    /* ---- 第二阶段：永远重启 shell ---- */

    for (;;) {
        pid = fork();
        if (pid < 0) {
            fputs(2, "init: fork failed\n");
            /* fork 失败（进程表满了）不应该让 init 退出。等一下再试——
             * 但我们没有 sleep，所以只能靠 wait 来让出 CPU。
             *
             * 这里 wait 的作用有点微妙：如果有子进程僵着没被回收，wait
             * 会回收一个并腾出进程表的位置；如果根本没有子进程，我们的
             * wait 会怎样？见 user.h——它在没有子进程时返回 -1 而不是
             * 阻塞（否则就是永久死锁）。所以这一行在最坏情况下是空转,
             * 变成一个忙等循环。
             *
             * 一个真实内核会在这里 sleep 一小会儿。我们没有 sleep,
             * 而给 init 加一个 sleep 需要内核支持定时唤醒——那是 Lab10
             * 的内容。写在这里是为了说明"这个忙等是已知的、有代价的
             * 妥协"，不是没想到。 */
            wait();
            continue;
        }
        if (pid == 0) {
            /* 交互式 shell：不带参数，所以 sh 会打提示符、从 fd 0 读。
             *
             * fd 0/1/2 是从 init 继承来的，而 init 的这三个 fd 是内核在
             * 创建第一个进程时直接接到控制台的（见 proc.c）。所以整条
             * 继承链是：内核 → init → sh → sh 的子进程，中间没有任何
             * 一步需要显式 open 控制台。
             *
             * 这就是为什么 Unix 程序可以假定 fd 0/1/2 一定可用：不是
             * 内核为每个进程都准备好，而是 pid 1 拿到了，之后靠 fork
             * 一路复制下去。这个链条上任何一环把它们关掉，后面的所有
             * 进程就都没有标准输入输出了——这是真实存在的一类故障
             * （守护进程忘了在 daemonize 时重新打开 /dev/null）。 */
            char *sh_argv[] = { "sh", NULL };
            exec("/sh", sh_argv);
            fputs(2, "init: exec /sh failed\n");
            exit(1);
        }

        /* 等这个 shell 结束，然后循环，再起一个。
         *
         * 自动化测试跑到这里就停住了：交互式 sh 阻塞在 read(0) 上，而
         * 测试不喂标准输入，控制台的 read 永远不会返回 EOF（UART 没有
         * "文件结束"这个概念，见 user.h）。于是 QEMU 一直运行到超时,
         * 测试脚本按超时退出码 124 判定通过。
         *
         * 这个安排是刻意的，而且它比"跑完就关机"更好：它证明了系统在
         * 跑完所有测试内容之后仍然是活的、可交互的。如果内核在某个地方
         * 留了状态损坏，"还能继续正常阻塞等输入"这件事本身就是一个检查。
         *
         * 手工运行时（scripts/run-qemu.sh）到这里会出现 `$ ` 提示符,
         * 可以直接敲 ls / cat / echo 试。 */
        wait();
    }

    /* 到不了这里。写一个 return 是为了让编译器不抱怨——实际上 for(;;)
     * 之后的代码不可达，GCC 知道这一点，所以这个 return 连指令都不会
     * 生成。 */
    return 0;
}
