/* Lab9：cat —— 把输入原样搬到输出。
 *
 * cat 是 Unix 工具里最能说明"一切皆文件描述符"的一个，因为它的代码里
 * 完全没有"文件"或"管道"或"终端"这些概念——只有一个 fd 上的 read 和另一个
 * fd 上的 write。同一份代码在三种场合下表现不同，而区别全在于 shell 把
 * 什么接到了 fd 0 和 fd 1 上：
 *
 *     cat motd.txt          fd 0 = 控制台（没用到），命令行给了文件名
 *     cat < motd.txt        fd 0 = 文件（shell 重定向），没有文件名参数
 *     echo hi | cat         fd 0 = 管道读端，没有文件名参数
 *
 * 后两种情况里 cat 走的是完全相同的代码路径。这不是巧合，是 fd 抽象的
 * 全部意义所在：read(0, ...) 的实现由内核按 fd 的类型分发，用户程序不
 * 需要知道也不应该知道。
 *
 * 它还是本 Lab 里唯一一个必须同时处理"有参数"和"无参数"两条路径的程序,
 * 因为这两条路径对应的正是"程序自己 open 文件"和"shell 替它准备好 fd"
 * 这两种得到输入的方式。
 */
#include "user.h"

/* 缓冲区大小 512 = 一个磁盘块，也是我们 pipe 的容量。
 *
 * 选它不是必须，但有两个好处：读文件时每次 read 刚好对齐一个块（内核
 * 少做一次跨块拼接）；读管道时一次 read 能把管道抽空，不会出现"读一半
 * 剩一半"的中间状态。
 *
 * 放在全局（.bss）而不是栈上：用户栈只有一个页（4 KiB，见 proc.c 的
 * USER_STACK_PAGES），一个 512 字节的局部数组占掉八分之一，而且真实
 * 的 cat 缓冲区常常是几十 KiB——那种大小放栈上就一定要出事。把大缓冲区
 * 放静态区是系统程序里的常规做法，理由就是栈的预算远比数据段紧。
 *
 * 代价是这样的程序不可重入（多线程下两个 cat 会互相踩），我们没有线程,
 * 不需要在意。 */
static char buf[512];

/* 把一个已经打开的 fd 抽干，全部写到 fd 1。
 *
 * 这个函数体是整个程序的核心，一共四行，而它的正确性依赖三件事：
 *
 *   1. read 返回 0 表示"没有更多数据了"。注意这跟"这次没读到数据"不是
 *      一回事——我们的 read 在管道空但写端还开着时会阻塞而不是返回 0
 *      （见 user.h 里关于三种 EOF 语义的说明）。如果它返回 0，`echo hi |
 *      cat` 里的 cat 会在 echo 还没来得及写之前就认为输入结束了。
 *
 *   2. read 返回的字节数可能小于请求的字节数，即使还没到末尾。文件读到
 *      最后一块、管道里只有几个字节、终端上用户只敲了一行——都会短读。
 *      所以 write 必须用 read 的返回值 n 作长度，不能用 sizeof(buf)。
 *      这是新手最常写错的一行，而且错了以后症状是输出末尾多出一堆上次
 *      残留的垃圾字节，看起来像"缓冲区没清零"，容易往错的方向查。
 *
 *   3. 负返回值是错误，要跟 0 区分开。用 `while ((n = read(...)) > 0)`
 *      把 0 和负数一起当作循环结束条件，是简洁但略有代价的写法：出错和
 *      正常结束变得无法区分。我们下面显式分开处理，因为 cat 的返回值要
 *      能告诉 shell 出没出错。
 */
static int copy_fd(int fd)
{
    int n;

    for (;;) {
        n = read(fd, buf, sizeof(buf));
        if (n == 0) {
            return 0;               /* 正常读完 */
        }
        if (n < 0) {
            fputs(2, "cat: read error\n");
            return -1;
        }
        /* 用 n，不是 sizeof(buf)。见上面第 2 点。
         *
         * 这里还有一个被我们简化掉的问题：write 也可能短写（返回值小于
         * n），真实的 cat 必须循环写直到 n 个字节全部写出。我们的内核里
         * write 要么全写完要么报错（控制台是同步的，管道写满会阻塞而不是
         * 短写），所以不需要这个循环。这是一处"因为内核的保证更强，所以
         * 用户程序可以更简单"的例子——但它是我们内核的保证，不是 POSIX
         * 的保证，代码搬到真实系统上就要补上循环。 */
        if (write(1, buf, n) != n) {
            fputs(2, "cat: write error\n");
            return -1;
        }
    }
}

int main(int argc, char **argv)
{
    int rc = 0;

    /* 没有参数：从标准输入读。
     *
     * 这一行让 `cat < f` 和 `echo x | cat` 都能工作，而且不需要任何额外
     * 代码——fd 0 已经是 shell 安排好的东西了。 */
    if (argc <= 1) {
        return copy_fd(0) < 0 ? 1 : 0;
    }

    /* 有参数：逐个打开、抽干、关闭。
     *
     * 多个文件名时输出是拼接起来的（这就是 cat 名字的来源：concatenate）。
     * 注意即使某个文件打不开，也要继续处理后面的——这是 coreutils 的行为,
     * 理由是 `cat a b c` 里 b 不存在时，用户大概还是想看到 a 和 c。只是
     * 退出码要记成失败。 */
    for (int i = 1; i < argc; i++) {
        int fd = open(argv[i]);
        if (fd < 0) {
            /* 错误信息写 fd 2 而不是 fd 1。
             *
             * 我们的 fd 2 和 fd 1 都指向控制台，所以现在看不出区别。但
             * 一旦有了重定向，区别就是决定性的：`cat nosuch > out` 应该
             * 让错误信息出现在屏幕上而不是被写进 out 里。把诊断信息和
             * 正常输出分成两个 fd，正是 stderr 存在的唯一理由。
             *
             * 本 Lab 的 sh 不支持输出重定向（文件系统是只读的），所以这
             * 条区别暂时观察不到——但代码现在就该写对，否则将来加上 `>`
             * 的时候要回来改每一个程序。 */
            fputs(2, "cat: cannot open ");
            fputs(2, argv[i]);
            fputs(2, "\n");
            rc = 1;
            continue;
        }
        if (copy_fd(fd) < 0) {
            rc = 1;
        }
        /* close 必须有：fd 表每个进程只有 NOFILE(8) 项，`cat a b c d e f
         * g h i` 会在第 9 个文件上失败。这类泄漏在短命的程序里通常无害
         * （进程退出时内核会清理），但 cat 恰好是可能被喂很多文件名的
         * 程序，而且 shell 是长命进程——泄漏在那边是真问题。 */
        close(fd);
    }
    return rc;
}
