/* Lab9：sh —— 极简 shell。
 *
 * shell 是本 Lab 的主角，因为它是第一个把前面所有系统调用组合起来用的
 * 程序。它自己不做任何"功能"——不读文件、不算东西、不访问硬件——它做的
 * 全部事情是：读一行、切成词、fork、调整子进程的 fd、exec、wait。
 *
 * 这个"什么都不做"正是它的意义。Unix 的设计把"决定运行什么程序、把它们
 * 的输入输出接到哪里"这件事从内核里拿出来，放进一个普通的用户程序。对比
 * 一下：在没有这层分离的系统上，"把 A 的输出接到 B 的输入"要么是内核的
 * 一个功能，要么根本不存在。
 *
 * 一个 shell 需要的全部内核支持，就是本 Lab 实现的那几个系统调用。反过来
 * 说：如果 fork/exec/pipe/dup 这四个里少任何一个，shell 就写不出来。
 * 值得逐个想一遍为什么：
 *
 *   没有 fork  → 运行一个命令就得放弃 shell 自己（exec 会覆盖当前进程）。
 *                这就是 MS-DOS 的 COMMAND.COM 的处境：它靠把自己的一部分
 *                驻留在内存里、运行完子程序再重新加载自己来绕过。
 *   没有 exec  → fork 出来的子进程只能是 shell 的副本，没法变成别的程序。
 *   没有 pipe  → 只能一个命令跑完写进文件、下一个再读，中间没有并发。
 *   没有 dup   → 有管道也接不上去，因为子程序写死了 write(1, ...)。
 *
 * "fork 然后 exec"这个两步走的组合常被批评为低效（创建一个地址空间只是
 * 为了立刻丢掉它），后来才有 posix_spawn / vfork / clone 这些替代品。但
 * 它换来的是下面这段代码的形状：fork 之后、exec 之前那个窗口里，子进程
 * 仍然在运行 shell 自己的代码，可以任意调整自己的状态（改 fd、改工作
 * 目录、改信号处理），然后才变成目标程序。所有这些调整用的都是普通的
 * 系统调用，不需要 exec 提供任何参数。一步式的 spawn 必须把每一种可能
 * 的调整都做成参数，接口会长得多——posix_spawn 有一整套 file_actions
 * API 就是这个原因。
 *
 * 本 shell 支持的语法
 * ------------------
 *     命令 参数...                    执行一个程序
 *     命令 < 文件                     输入重定向
 *     命令 | 命令                     管道（只支持一级，两个进程）
 *
 * 不支持：引号、转义、多级管道、输出重定向（>）、后台执行（&）、
 * 变量、通配符、内建命令（cd 等）、控制结构。
 *
 * 为什么不支持输出重定向：因为本 Lab 的文件系统是只读的（见 fs.h）。
 * 这是一个值得注意的不对称——`<` 和 `>` 在语法上完全对称，解析代码几乎
 * 一样，但 `>` 需要的内核支持（创建文件、分配块、写回位图、扩展 inode）
 * 是 `<` 的好几倍。语法的对称性和实现代价的对称性没有任何关系，而人很
 * 容易从前者推测后者。
 *
 * 为什么只支持一级管道：多级管道（a | b | c）需要在循环里反复 pipe+fork,
 * 而且 shell 必须小心地关掉自己手上所有用不到的管道端——漏关一个，下游
 * 就永远等不到 EOF，整条命令挂住。那个簿记是真实 shell 里最容易出错的
 * 部分之一，值得单独作为挑战任务，而一级管道已经足够把 pipe + dup 的
 * 机制讲完整。
 */
#include "user.h"

/* ------------------------------------------------------------------ */
/* 全局状态                                                           */
/* ------------------------------------------------------------------ */

/* 输入行缓冲区。放在 .bss（全局未初始化）而不是 main 的栈上，有两个原因:
 *
 *   1. 用户栈只有一个页（4 KiB）。这里的 buf + argv 数组 + 下面那些
 *      指针加起来几百字节，放栈上不会当场溢出，但 shell 是唯一会长期
 *      运行并且不断调用函数的用户程序，给它留余量是值得的。
 *
 *   2. 更重要的教学理由：这让 sh 成为本 Lab 里唯一真正拥有 .bss 段的
 *      程序。ELF 加载器必须正确处理 p_memsz > p_filesz（把多出来的
 *      字节清零），而这个性质只有在某个程序真的有 .bss 时才会被测到。
 *      如果六个程序全都只有 .text/.rodata，加载器里清零那段代码就是
 *      死代码，写错了也没人知道——直到某天有人加了一个全局数组。
 *
 *      "让每条代码路径都至少被一个测试覆盖到"这件事，在写内核时要靠
 *      刻意安排测试数据来实现。这里的安排就是：故意把缓冲区放到 .bss。
 */
static char buf[128];

/* 提示符。两处用到它：交互模式下每轮循环打一次，脚本模式下回显命令时
 * 作为前缀。两处是同一个东西，所以只该有一个定义。
 *
 * 声明成 `static char prompt[] = "$ "` 而不是 `const char *prompt = "$ "`,
 * 差别不只是风格——前者是一个 3 字节的可写数组，放在 .data；后者是一个
 * 指向 .rodata 的指针，指针本身在 .data，字符串在 .rodata。
 *
 * 选前者，顺带解决了一个测试覆盖问题。ELF 加载器对每个 PT_LOAD 段要处理
 * 三种情况：
 *
 *     p_filesz == p_memsz        纯代码/只读数据，整段从文件拷
 *     p_filesz == 0, p_memsz > 0 纯 .bss，整段清零，不读文件
 *     0 < p_filesz < p_memsz     .data 后面紧跟 .bss，前半拷、后半清零
 *
 * 前两种情况本 Lab 的六个程序都覆盖到了（ls/echo 只有第一种，cat/grep
 * 的 RW 段是第二种）。第三种没有任何程序产生——因为没有一个程序有初始化
 * 过的全局变量。而第三种恰恰是最容易写错的：清零的起点必须是
 * p_vaddr + p_filesz，写成 p_vaddr 就会把刚拷进去的 .data 抹成 0。
 *
 * 那个 bug 的症状：初始化过的全局变量的初值全变成 0。对 prompt 来说就是
 * 提示符消失（变成空字符串），而程序其它部分完全正常——很容易归因到
 * "提示符没打出来"这个表层现象上去。
 *
 * 所以把提示符做成 .data 里的可写数组，是一个"顺手让这条代码路径被测到"
 * 的安排。跟下面 buf 放 .bss 的理由是同一类：内核里有些分支只有当输入
 * 数据恰好具备某种形状时才会走到，那种形状要靠刻意安排测试数据来造。
 *
 * （可写也不是纯粹的借口：真实 shell 的提示符是可以改的，PS1 就是那个
 * 变量。我们没有环境变量，所以它只是恰好可写而没人改。） */
static char prompt[] = "$ ";

/* 切分后的参数数组。MAXARGS 个指针 + 结尾的 NULL。
 *
 * 10 个参数对本 Lab 够用。超出时下面会报错而不是静默截断——截断的症状是
 * "命令少收到几个参数"，而参数少了之后程序的行为往往仍然合理（比如 cat
 * 少读一个文件），错误会被当成正常输出接受下来。 */
#define MAXARGS 10
static char *argv_buf[MAXARGS + 1];

/* 解析结果。用一个结构体装起来，而不是一堆 out 参数，是因为解析函数要
 * 返回四样东西（argv、重定向文件名、管道右半边的位置、错误标志）。 */
struct cmd {
    char **argv;        /* 以 NULL 结尾的参数数组 */
    char  *infile;      /* `< 文件` 里的文件名，没有重定向时是 NULL */
    char  *pipe_rest;   /* `|` 右边那半条命令的起始位置，没有管道时 NULL */
};

/* ------------------------------------------------------------------ */
/* 读一行                                                             */
/* ------------------------------------------------------------------ */

/* 从 fd 读一行到 dst，去掉末尾的换行符，补上 '\0'。
 * 返回行的长度；返回 -1 表示 EOF（且没读到任何字符）。
 *
 * 一次 read 一个字节，这是本文件里效率最差的一处，但它是必须的：
 *
 * shell 读的是一个*交互式*输入流。如果一次 read 512 字节，内核会等到
 * 凑够 512 个字节或者 EOF 才返回（我们的控制台 read 不做行缓冲），而
 * 用户敲完一行按回车之后就期望命令立刻执行。也就是说，"读一行"这个
 * 需求和"一次读一大块"在没有行缓冲的情况下是冲突的。
 *
 * 真实系统怎么解决：终端驱动在内核里做行缓冲（termios 的 canonical
 * mode），read 在遇到换行符时就返回，哪怕请求的字节数更多。于是用户程序
 * 可以放心地 read 一大块。这是 tty 层存在的主要理由之一，也是为什么
 * `read` 一个终端和 `read` 一个文件的行为不一样。
 *
 * 我们把这件事放在用户态做（一次一个字节），代价是每个字符一次系统调用。
 * 好处是内核侧的控制台驱动可以保持极简——它只需要"读一个字符"，不需要
 * 理解行的概念、不需要处理退格、不需要回显策略。把复杂度放在哪一侧是
 * 一个真实的设计选择，两种做法都有系统采用（Plan 9 的 tty 处理就比
 * Unix 薄得多）。
 */
static int readline(int fd, char *dst, int max)
{
    int n = 0;

    for (;;) {
        char c;
        int  r = read(fd, &c, 1);

        if (r < 0) {
            return -1;
        }
        if (r == 0) {
            /* EOF。
             *
             * 注意这里区分"读到一半遇到 EOF"和"一开始就是 EOF"：前者
             * 应该把已经读到的内容当作最后一行处理（文件末尾可能没有
             * 换行符），后者才是真正的输入结束。
             *
             * 这个区分对脚本模式是必要的：如果 initrc 最后一行没有换行,
             * 不做区分就会丢掉那一行命令。 */
            if (n == 0) {
                return -1;
            }
            break;
        }
        if (c == '\n' || c == '\r') {
            /* '\r' 也当行结束：串口终端上回车键发的是 '\r'（CR），而不是
             * '\n'（LF）。QEMU 把 -serial 接到 stdio 时，从终端过来的
             * 回车是什么取决于宿主终端的设置，两个都收下最稳。
             *
             * 这不是假想的问题：只认 '\n' 的话，在 QEMU 里手工敲命令会
             * 发现回车完全没反应，而自动化测试（通过管道喂输入）却一切
             * 正常——因为管道里的换行是 '\n'。"交互时不工作、测试时工作"
             * 是最容易被忽略的一类 bug，因为跑测试的人看不到它。 */
            break;
        }

        /* 缓冲区留一格给 '\0'。满了就丢弃多余字符，但仍然要继续读到行
         * 结束——否则剩下的字符会被当成下一行命令，一行过长会变成"执行
         * 了一条莫名其妙的命令"。 */
        if (n < max - 1) {
            dst[n++] = c;
        }
    }

    dst[n] = '\0';
    return n;
}

/* ------------------------------------------------------------------ */
/* 解析                                                               */
/* ------------------------------------------------------------------ */

static int is_space(char c)
{
    return c == ' ' || c == '\t';
}

/* 就地切分一行，填好 cmd 结构。返回 0 成功，-1 失败（已打印错误）。
 *
 * "就地"（in-place）的意思是：直接在输入缓冲区里把分隔符改写成 '\0'，
 * argv 里的指针指向缓冲区内部，不做任何拷贝。真实 shell 也这么干。
 *
 * 这个技巧值得注意的一点是：它要求输入缓冲区在 exec 之前一直有效。这里
 * 是成立的（buf 是全局的，而且 exec 成功后子进程的整个地址空间都被
 * 替换掉了，argv 的内容早在 sys_exec 里被拷进内核了）。但如果 argv 指向
 * 的是一个已经返回了的函数的局部数组，就是一个悬空指针——而且因为栈上
 * 的旧数据往往还在，它能"正常工作"很长时间。
 */
static int parse(char *line, struct cmd *out)
{
    int argc = 0;

    out->argv      = argv_buf;
    out->infile    = NULL;
    out->pipe_rest = NULL;

    char *p = line;

    for (;;) {
        while (is_space(*p)) {
            p++;
        }
        if (*p == '\0') {
            break;
        }

        /* 管道符：把这里截断，右半边留给调用方递归处理。
         *
         * 注意 `|` 必须在解析参数*之前*检查，否则 "a | b" 里的 "|" 会
         * 被当成一个普通参数。我们要求 `|` 两边有空格（因为切词只按空白
         * 切），所以 "a|b" 解析不出管道——真实 shell 的词法分析会把 `|`
         * 当成独立的 token 而不管有没有空格。那需要一个真正的 tokenizer,
         * 而我们只有 strtok 级别的切分。这是本 shell 已知的限制，写在
         * README 的坑一节里。 */
        if (*p == '|') {
            *p = '\0';
            out->pipe_rest = p + 1;
            break;
        }

        /* 输入重定向：`<` 后面跟的是文件名，不进 argv。
         *
         * 同样要求 `<` 独立成词（"cmd < f" 而不是 "cmd <f"）。 */
        if (*p == '<') {
            *p = '\0';
            p++;
            while (is_space(*p)) {
                p++;
            }
            if (*p == '\0') {
                fputs(2, "sh: syntax error: expected filename after <\n");
                return -1;
            }
            out->infile = p;
            /* 文件名到下一个空白为止 */
            while (*p != '\0' && !is_space(*p)) {
                p++;
            }
            if (*p != '\0') {
                *p = '\0';
                p++;
            }
            continue;
        }

        if (argc >= MAXARGS) {
            fputs(2, "sh: too many arguments\n");
            return -1;
        }

        out->argv[argc++] = p;

        /* 词到下一个空白（或 `|`、`<`）为止。
         *
         * 把 `|` 和 `<` 也当作词的结束符，这样 "echo hi|grep h" 至少能把
         * "hi|grep" 切成一个词而不是吞掉后面整行——不过如上所述，那种写法
         * 本 shell 不支持。 */
        while (*p != '\0' && !is_space(*p) && *p != '|' && *p != '<') {
            p++;
        }
        if (is_space(*p)) {
            *p = '\0';
            p++;
        }
        /* 如果停在 '|' 或 '<' 上，不要消耗它，让下一轮循环去识别。 */
    }

    /* argv 必须以 NULL 结尾——这是 exec 判断参数个数的唯一依据。
     *
     * 忘了这一行的症状：内核的 sys_exec 会一直往下读，把 argv 数组后面
     * 栈上/bss 里的垃圾当成参数指针，然后拿它们去 strlen。可能崩，也可能
     * 读到一堆乱码参数。argv_buf 是 static 的（初值全 0），所以第一次
     * 恰好没问题，第二条命令参数变少时就会读到上一条命令残留的指针——
     * 又一个"第一次能跑"的 bug。 */
    out->argv[argc] = NULL;

    if (argc == 0 && out->pipe_rest == NULL && out->infile == NULL) {
        return 1;   /* 空行，不是错误 */
    }
    if (argc == 0) {
        fputs(2, "sh: syntax error: missing command\n");
        return -1;
    }
    return 0;
}

/* ------------------------------------------------------------------ */
/* 执行                                                               */
/* ------------------------------------------------------------------ */

/* 在*当前进程*里把 fd 调整好，然后 exec。这个函数只会被子进程调用，
 * 而且不返回（exec 成功就不回来，失败就 exit）。
 *
 * 注意它修改的是自己的 fd 表——这正是 fork/exec 两步走的价值所在：这些
 * 调整用的是普通的 open/close/dup，不需要 exec 有任何对应的参数。 */
static void run_child(struct cmd *c) __attribute__((noreturn));
static void run_child(struct cmd *c)
{
    /* 输入重定向。
     *
     * 顺序很重要：先 open 新文件，成功了再 close(0)，最后 dup 到 0。
     * 反过来（先 close(0) 再 open）看起来更省一步——因为 open 会返回最小
     * 空闲 fd，正好是刚关掉的 0，连 dup 都不用：
     *
     *     close(0);
     *     open(c->infile);      // 返回 0，直接就位
     *
     * 这个写法在成功时完全正确，而且真实 shell 有时就这么写。但失败时就
     * 麻烦了：fd 0 已经关掉，而新文件没打开，子进程带着一个空的 fd 0 去
     * exec。后面的程序 read(0) 会拿到 -1，表现成"输入是空的"而不是"文件
     * 打不开"。
     *
     * 先 open 再 close 的版本在失败时 fd 0 还是原样，可以干净地报错退出。
     * 多一次 dup 换一个明确的失败路径。 */
    if (c->infile != NULL) {
        int fd = open(c->infile);
        if (fd < 0) {
            fputs(2, "sh: cannot open ");
            fputs(2, c->infile);
            fputs(2, "\n");
            exit(1);
        }
        if (fd != 0) {
            close(0);
            if (dup(fd) != 0) {
                /* dup 应该返回最小空闲 fd，刚 close 了 0 所以必然是 0。
                 * 检查它是一种断言：如果内核的 dup 没实现"最小"语义,
                 * 这里会立刻炸出来，而不是让重定向静默失效。
                 *
                 * "静默失效"在这里的具体样子：dup 返回 3，于是 fd 0 仍然
                 * 是空的，程序从空 fd 读，输出为空。而 `cat < f` 输出为空
                 * 跟"文件是空的"看起来一模一样。 */
                fputs(2, "sh: dup did not return fd 0\n");
                exit(1);
            }
            close(fd);
        }
    }

    exec(c->argv[0], c->argv);

    /* exec 只在失败时返回。
     *
     * 这是 exec 接口一个很特别的性质：成功的路径上它没有返回值可言,
     * 因为调用它的那个程序已经不存在了。所以不需要检查返回值——能走到
     * 下一行就说明失败了。
     *
     * 一个常见的误写是 `if (exec(...) < 0) { ... }`，然后在 if 外面继续
     * 写代码。那些代码在成功时永远不执行，在失败时会执行两次（一次在
     * if 里报错，一次在 if 外面继续跑）。 */
    fputs(2, "sh: exec ");
    fputs(2, c->argv[0]);
    fputs(2, " failed\n");
    exit(1);
}

/* 执行一条（可能带管道的）命令。在父进程里调用，会 wait 到全部子进程
 * 结束才返回。 */
static void run_cmd(struct cmd *left)
{
    /* ---- 没有管道：最简单的情况 ---- */
    if (left->pipe_rest == NULL) {
        int pid = fork();
        if (pid < 0) {
            fputs(2, "sh: fork failed\n");
            return;
        }
        if (pid == 0) {
            run_child(left);    /* 不返回 */
        }
        wait();
        return;
    }

    /* ---- 有管道：a | b ---- */

    /* 先把右半边解析出来。
     *
     * 注意这里用的是同一个 argv_buf——所以必须在 fork 左半边*之前*就
     * 解析完吗？不，恰恰相反：必须在 fork 之后、由各自的子进程独立处理,
     * 或者在父进程里分两次用。我们采取的办法是：
     *
     *   - 先 fork 左半边的子进程。它此时 argv_buf 里装的是左半边，直接
     *     用（fork 出来的是副本，父进程后面怎么改都影响不到它）。
     *   - 父进程再解析右半边（覆盖 argv_buf），fork 第二个子进程。
     *
     * 这就是 fork 的语义在实践中的一个具体好处：父进程不需要为两个子
     * 进程各准备一份参数数组，因为 fork 的那一刻子进程就拿到了独立的
     * 副本。共享内存的线程模型下同样的代码会有数据竞争。 */

    int fds[2];
    if (pipe(fds) < 0) {
        fputs(2, "sh: pipe failed\n");
        return;
    }
    /* fds[0] 是读端，fds[1] 是写端。这个顺序跟 POSIX 一致，
     * 助记：0 是 stdin（读），1 是 stdout（写）。 */

    char *rest = left->pipe_rest;

    /* --- 左半边：输出接到管道写端 --- */
    int pid1 = fork();
    if (pid1 < 0) {
        fputs(2, "sh: fork failed\n");
        close(fds[0]);
        close(fds[1]);
        return;
    }
    if (pid1 == 0) {
        /* 子进程：把 fd 1 换成管道写端。
         *
         * close(1) 之后 dup(fds[1]) 返回 1（最小空闲）。这套手法的细节
         * 见 syscall.h 里 SYS_DUP 的注释。 */
        close(1);
        if (dup(fds[1]) != 1) {
            fputs(2, "sh: dup did not return fd 1\n");
            exit(1);
        }

        /* 关掉两个原始管道 fd。
         *
         * 这两行是整个管道实现里最容易漏、漏了最难查的部分，值得分开说:
         *
         *   close(fds[1])：fd 1 现在也指向写端了，原来那个号是多余的。
         *   不关的后果比"浪费一个 fd"严重得多——见下面对读端的说明，
         *   写端的引用计数决定了下游什么时候看到 EOF。
         *
         *   close(fds[0])：左半边根本不读管道，但它从 fork 继承了读端。
         *   不关的后果：如果右半边先退出，管道就满了之后没人读，左半边
         *   会永远阻塞在 write 上——而它手上恰好还攥着一个读端，所以
         *   内核也没法判断"读端全关了，该让写方报错"。
         *
         * 共同的教训是：管道的 EOF 和"写端关闭"检测，靠的是内核数一数
         * 还有几个 fd 指向这一端（我们的 struct pipe 里的 nread_open /
         * nwrite_open）。fork 会把父进程的每一个 fd 都复制给子进程，所以
         * 每个进程都必须显式关掉自己用不到的那些端，引用计数才能降到 0。
         *
         * 漏关的典型症状：命令挂住不返回，看起来像死锁——它确实是死锁,
         * 但成因不在代码的控制流里，而在"某个进程手上还有一个它自己都
         * 不知道的 fd"。 */
        close(fds[1]);
        close(fds[0]);

        run_child(left);        /* 不返回 */
    }

    /* --- 右半边：输入接到管道读端 --- */

    /* 父进程解析右半边。复用 argv_buf 是安全的——左半边的子进程已经有
     * 自己的副本了。 */
    struct cmd right;
    int pr = parse(rest, &right);
    if (pr != 0) {
        /* 解析失败或右半边是空的（`cat f |`）。
         *
         * 必须把两个管道端都关掉再 wait，否则左半边会卡在 write 上：
         * 没有进程读管道，而父进程手上还有读端，内核认为"读端还开着"。 */
        if (pr > 0) {
            fputs(2, "sh: syntax error: missing command after |\n");
        }
        close(fds[0]);
        close(fds[1]);
        wait();
        return;
    }

    int pid2 = fork();
    if (pid2 < 0) {
        fputs(2, "sh: fork failed\n");
        close(fds[0]);
        close(fds[1]);
        wait();
        return;
    }
    if (pid2 == 0) {
        /* 右半边的输入重定向（`cat < f | grep x` 里的 `< f` 属于左边,
         * 但 `a | grep x < f` 这种写法也允许）优先于管道——实际上如果
         * 两者都有，run_child 里的 open/dup 会再次替换 fd 0，覆盖掉
         * 管道。真实 shell 的行为也是"后面的重定向覆盖前面的"。 */
        close(0);
        if (dup(fds[0]) != 0) {
            fputs(2, "sh: dup did not return fd 0\n");
            exit(1);
        }
        close(fds[0]);
        close(fds[1]);
        run_child(&right);     /* 不返回 */
    }

    /* --- 父进程：关掉两端，等两个孩子 --- */

    /* 父进程自己既不读也不写管道，两端都要关。
     *
     * 这两行同样是必须的，而且是最经典的一处遗漏。考虑 `cat big | grep x`:
     * 如果父进程不关写端，那么即使左半边（cat）已经退出了，管道的写端
     * 引用计数仍然是 1（父进程手上那个），于是 grep 的 read 永远等不到
     * EOF——它会一直阻塞。
     *
     * 症状：命令执行完了，输出也对，但 shell 不返回提示符。看起来像
     * "grep 有 bug"，实际上是 shell 少关了一个 fd。这个 bug 的诡异之处
     * 在于：出问题的进程（grep）完全正常，肇事者（sh）看起来什么都没做。 */
    close(fds[0]);
    close(fds[1]);

    /* 两个孩子，wait 两次。
     *
     * 我们的 wait() 不返回退出码也不能指定 pid（见 user.h），所以这里
     * 只能"等两次"，拿不到"哪个先结束"。真实 shell 需要知道管道最后一个
     * 命令的退出码（那是整条管道的退出码），得用 waitpid。
     *
     * 一个容易想当然的假设：左半边先结束。不一定——`yes | head -1` 里
     * 右半边先结束，然后左半边因为写端没人读而收到 SIGPIPE。我们没有
     * 信号，所以那种情况下左半边会阻塞在 write 上，而父进程卡在第二个
     * wait 上，整体挂住。这是本 Lab 的一个真实局限，见 README。 */
    (void)pid1;
    (void)pid2;
    wait();
    wait();
}

/* ------------------------------------------------------------------ */
/* main                                                               */
/* ------------------------------------------------------------------ */

int main(int argc, char **argv)
{
    /* 两种运行模式：
     *
     *   sh              交互模式：打印提示符，从 fd 0 读命令
     *   sh <脚本文件>   脚本模式：从文件读命令，回显每一条，不打提示符
     *
     * 脚本模式存在的唯一理由是自动化测试。测试脚本（scripts/test-lab.sh）
     * 不给 QEMU 喂标准输入（见那个脚本的注释），所以交互模式下 shell 会
     * 阻塞在 read(0) 上永远等不到输入——测试跑不起来。
     *
     * 那为什么不让测试喂输入？因为两个架构的控制台输入都是 UART 轮询
     * （见本 Lab 的 README），而"通过管道往 QEMU 的串口喂字节、恰好在
     * 内核已经准备好读的时候到达"这件事是有时序竞争的：喂得太早，字节
     * 在内核初始化完之前就到了 UART 的接收寄存器，可能被覆盖；喂得太
     * 晚，测试已经超时。这类竞争会让测试偶尔失败，而偶尔失败的测试比
     * 没有测试更糟。
     *
     * 脚本模式把输入源从"外部时序"变成"磁盘上的一个文件"，整条测试路径
     * 就完全确定了。这是一个值得记住的测试设计手法：把不确定的输入源
     * 换成确定的，哪怕要为此在被测程序里加一个模式。
     *
     * 回显每条命令（脚本模式下）也是为了测试：没有回显的话，期望输出
     * 里只有各命令的结果，看不出它们是哪条命令产生的，而且一条命令完全
     * 没执行（比如 exec 失败）时期望文件里少一段输出，很难定位。 */
    int script_mode = (argc > 1);
    int in_fd       = 0;

    if (script_mode) {
        in_fd = open(argv[1]);
        if (in_fd < 0) {
            fputs(2, "sh: cannot open script ");
            fputs(2, argv[1]);
            fputs(2, "\n");
            return 1;
        }
    }

    for (;;) {
        if (!script_mode) {
            puts(prompt);
        }

        int n = readline(in_fd, buf, sizeof(buf));
        if (n < 0) {
            break;      /* EOF */
        }

        if (script_mode) {
            /* 回显：把这一行原样打出来，前面加提示符，让输出能跟脚本
             * 对照着看。 */
            puts(prompt);
            puts(buf);
            puts("\n");
        }

        /* 注释行和空行直接跳过。注释支持只是为了让 initrc 能自我说明。 */
        if (buf[0] == '#') {
            continue;
        }

        struct cmd c;
        int rc = parse(buf, &c);
        if (rc < 0) {
            continue;   /* 语法错误，已报告 */
        }
        if (rc > 0) {
            continue;   /* 空行 */
        }

        run_cmd(&c);
    }

    if (script_mode) {
        close(in_fd);
    }
    return 0;
}
